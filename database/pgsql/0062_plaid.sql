-- Plaid items keep the access token encrypted. Mapping a Plaid account to a
-- dashboard account does not copy a balance. plaid_transaction_id dedupes
-- imports so a later sync does not insert the same row again.

CREATE TABLE money_plaid_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_id                 VARCHAR(80) NOT NULL,
    institution_id          VARCHAR(80),
    institution_name        VARCHAR(120) NOT NULL,
    access_token_encrypted  TEXT NOT NULL,
    transactions_cursor     TEXT,
    status                  VARCHAR(24) NOT NULL DEFAULT 'good'
                            CHECK (status IN ('good', 'login_required', 'error')),
    sync_error              TEXT,
    last_synced_at          TIMESTAMP(0),
    created_at              TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at              TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, item_id)
);
CREATE INDEX idx_money_plaid_items_user ON money_plaid_items (user_id);

CREATE TABLE money_plaid_accounts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item_row_id       BIGINT NOT NULL REFERENCES money_plaid_items(id) ON DELETE CASCADE,
    plaid_account_id  VARCHAR(80) NOT NULL,
    name              VARCHAR(120) NOT NULL,
    mask              CHAR(4),
    plaid_type        VARCHAR(32),
    plaid_subtype     VARCHAR(32),
    account_id        BIGINT REFERENCES money_accounts(id) ON DELETE SET NULL,
    created_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, plaid_account_id)
);
CREATE INDEX idx_money_plaid_accounts_item ON money_plaid_accounts (item_row_id);
CREATE UNIQUE INDEX idx_money_plaid_accounts_dashboard
    ON money_plaid_accounts (user_id, account_id)
    WHERE account_id IS NOT NULL;

ALTER TABLE money_accounts
    ADD COLUMN available_balance DOUBLE PRECISION;

ALTER TABLE money_transactions
    ADD COLUMN plaid_transaction_id VARCHAR(80);

CREATE UNIQUE INDEX idx_money_tx_plaid
    ON money_transactions (user_id, plaid_transaction_id)
    WHERE plaid_transaction_id IS NOT NULL;

CREATE TRIGGER trg_money_plaid_items_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_plaid_items
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_plaid_accounts_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_plaid_accounts
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
