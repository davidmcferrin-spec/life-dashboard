-- =====================================================================
-- L2: scoped bearer tokens for /api/v1 and an append-only audit log.
-- Tokens store SHA-256 only. The plaintext is shown once at creation.
-- audit_events.user_id lets lifedash_notify fan the row out to that user.
-- =====================================================================

CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name         VARCHAR(64)  NOT NULL,
    prefix       VARCHAR(16)  NOT NULL,
    token_hash   CHAR(64)     NOT NULL UNIQUE,
    scopes       TEXT         NOT NULL,
    expires_at   TIMESTAMP(0),
    last_used_at TIMESTAMP(0),
    revoked_at   TIMESTAMP(0),
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_api_tokens_user ON api_tokens(user_id, created_at DESC);

CREATE TABLE audit_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor      VARCHAR(16)  NOT NULL CHECK (actor IN ('user', 'ai', 'system', 'integration')),
    tool       VARCHAR(64),
    action     VARCHAR(64)  NOT NULL,
    resource   VARCHAR(160),
    detail     JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_audit_events_user_created ON audit_events(user_id, created_at DESC);
CREATE INDEX idx_audit_events_resource ON audit_events(user_id, resource);

CREATE TRIGGER trg_audit_events_notify
    AFTER INSERT ON audit_events
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
