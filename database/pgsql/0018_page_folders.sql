-- Nested folders for the vault. Existing pages stay at the root (folder_id null).
-- A folder can be deleted only when it is empty, or after its pages and child folders
-- move to the parent. Sibling names are unique, ignoring case.

CREATE TABLE page_folders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    parent_id  BIGINT       REFERENCES page_folders(id) ON DELETE RESTRICT,
    name       VARCHAR(80)  NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE UNIQUE INDEX page_folders_sibling_name
    ON page_folders (user_id, COALESCE(parent_id, 0), lower(name));

CREATE INDEX idx_page_folders_parent ON page_folders (user_id, parent_id);

ALTER TABLE pages
    ADD COLUMN folder_id BIGINT REFERENCES page_folders(id) ON DELETE SET NULL;

CREATE INDEX idx_pages_folder ON pages (user_id, folder_id) WHERE archived_at IS NULL;
