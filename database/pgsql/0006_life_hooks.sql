-- =====================================================================
-- L3: Home Assistant (and similar) webhook secrets.
-- The URL carries the plaintext once; only the SHA-256 is stored.
-- =====================================================================

CREATE TABLE life_hooks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(64) NOT NULL DEFAULT 'Home Assistant',
    prefix     VARCHAR(16) NOT NULL,
    token_hash CHAR(64)    NOT NULL UNIQUE,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    revoked_at TIMESTAMP(0)
);
CREATE INDEX idx_life_hooks_user ON life_hooks(user_id, created_at DESC);
