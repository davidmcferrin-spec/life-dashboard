-- Daily bars copied from the History tab, and one price per symbol per hour.
-- The sheet drops days older than a year and can return blanks while GOOGLEFINANCE reloads.
-- Neither case deletes a row or replaces a stored number. The sheet is never written.

CREATE TABLE stock_sheet_bars (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    symbol       VARCHAR(32) NOT NULL,
    bar_date     DATE NOT NULL,
    open_price   DOUBLE PRECISION,
    high_price   DOUBLE PRECISION,
    low_price    DOUBLE PRECISION,
    close_price  DOUBLE PRECISION,
    volume       DOUBLE PRECISION,
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, symbol, bar_date)
);

CREATE TABLE stock_sheet_ticks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    symbol       VARCHAR(32) NOT NULL,
    captured_at  TIMESTAMP(0) NOT NULL,
    price        DOUBLE PRECISION,
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, symbol, captured_at)
);

CREATE TRIGGER trg_stock_sheet_bars_notify
    AFTER INSERT OR UPDATE OR DELETE ON stock_sheet_bars
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_stock_sheet_ticks_notify
    AFTER INSERT OR UPDATE OR DELETE ON stock_sheet_ticks
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
