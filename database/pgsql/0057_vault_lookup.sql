-- Former titles stay findable after a rename. Page bodies and saved revisions are not rewritten.
-- updated_by names the token or user that last wrote the page. Existing rows stay blank
-- until the audit log can name them.

ALTER TABLE pages
    ADD COLUMN updated_by VARCHAR(80) NOT NULL DEFAULT '';

CREATE TABLE page_titles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    page_id    BIGINT       NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    title      VARCHAR(200) NOT NULL,
    slug       VARCHAR(200),
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE INDEX idx_page_titles_user_title ON page_titles (user_id, lower(title));
CREATE INDEX idx_page_titles_page ON page_titles (page_id, created_at DESC);

INSERT INTO page_titles (user_id, page_id, title, created_at)
SELECT DISTINCT ON (r.user_id, r.page_id, lower(r.title))
    r.user_id,
    r.page_id,
    r.title,
    r.created_at
FROM page_revisions r
JOIN pages p ON p.id = r.page_id AND p.user_id = r.user_id
WHERE lower(r.title) <> lower(p.title)
ORDER BY r.user_id, r.page_id, lower(r.title), r.created_at DESC;

UPDATE pages AS p
SET updated_by = src.label
FROM (
    SELECT DISTINCT ON (page_id)
        page_id,
        label
    FROM (
        SELECT
            substring(resource FROM '^page:([0-9]+)$')::bigint AS page_id,
            COALESCE(NULLIF(detail->>'token_name', ''), actor) AS label,
            id
        FROM audit_events
        WHERE resource ~ '^page:[0-9]+$'
          AND action IN ('page.create', 'page.update', 'page.move', 'page.archive', 'page.restore')
    ) AS events
    ORDER BY page_id, id DESC
) AS src
WHERE p.id = src.page_id
  AND p.updated_by = '';
