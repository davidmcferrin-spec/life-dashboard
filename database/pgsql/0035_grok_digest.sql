-- Changelog sources and the entries parsed from them.
-- digest_cursors has an id so lifedash_notify can name the row.

CREATE TABLE digest_sources (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product        VARCHAR(16)  NOT NULL
                   CHECK (product IN ('cursor_ide', 'grok_bot', 'grok', 'grok_build')),
    label          VARCHAR(80)  NOT NULL,
    url            TEXT         NOT NULL,
    enabled        SMALLINT     NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
    etag           TEXT,
    last_modified  TEXT,
    last_checked_at TIMESTAMP(0),
    status         VARCHAR(24)  NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'ok', 'needs_attention')),
    last_error     TEXT,
    parse_mode     VARCHAR(8),
    content_hash   TEXT,
    created_at     TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, url)
);

CREATE TABLE digest_entries (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_id    BIGINT       NOT NULL REFERENCES digest_sources(id) ON DELETE CASCADE,
    entry_key    VARCHAR(200) NOT NULL,
    title        VARCHAR(300) NOT NULL,
    published_on DATE,
    url          TEXT         NOT NULL,
    summary      TEXT         NOT NULL DEFAULT '',
    content_hash CHAR(64)     NOT NULL,
    first_seen_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    edited_at    TIMESTAMP(0),
    UNIQUE (source_id, entry_key)
);
CREATE INDEX idx_digest_entries_user_seen ON digest_entries (user_id, first_seen_at DESC);

CREATE TABLE digest_cursors (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    read_through_at TIMESTAMP(0) NOT NULL
);

CREATE TRIGGER trg_digest_sources_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_sources
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_digest_entries_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_entries
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_digest_cursors_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_cursors
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
