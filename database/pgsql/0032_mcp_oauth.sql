-- MCP OAuth 2.1 clients, authorization codes, and rotating tokens.
-- 0031 is the Spotify migration on the other branch. Filename order applies
-- both files whichever pull request merges first.
-- Plaintext secrets are never stored. Access and refresh tokens are SHA-256.

CREATE TABLE oauth_clients (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT       REFERENCES users(id) ON DELETE CASCADE,
    client_id          VARCHAR(64)  NOT NULL UNIQUE,
    client_name        VARCHAR(120) NOT NULL,
    redirect_uris      JSONB        NOT NULL,
    registered_scopes  JSONB        NOT NULL DEFAULT '[]'::jsonb,
    granted_scopes     JSONB        NOT NULL DEFAULT '[]'::jsonb,
    last_used_at       TIMESTAMP(0),
    revoked_at         TIMESTAMP(0),
    created_at         TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_oauth_clients_user ON oauth_clients (user_id, created_at DESC);

CREATE TABLE oauth_authorization_codes (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_id              BIGINT       NOT NULL REFERENCES oauth_clients(id) ON DELETE CASCADE,
    code_hash              CHAR(64)     NOT NULL UNIQUE,
    redirect_uri           TEXT         NOT NULL,
    code_challenge         VARCHAR(128) NOT NULL,
    code_challenge_method  VARCHAR(8)   NOT NULL,
    scopes                 JSONB        NOT NULL,
    resource               TEXT,
    expires_at             TIMESTAMP(0) NOT NULL,
    used_at                TIMESTAMP(0),
    created_at             TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE oauth_tokens (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_id              BIGINT       NOT NULL REFERENCES oauth_clients(id) ON DELETE CASCADE,
    token_hash             CHAR(64)     NOT NULL UNIQUE,
    refresh_hash           CHAR(64)     UNIQUE,
    previous_refresh_hash  CHAR(64),
    scopes                 JSONB        NOT NULL,
    access_expires_at      TIMESTAMP(0) NOT NULL,
    refresh_expires_at     TIMESTAMP(0) NOT NULL,
    revoked_at             TIMESTAMP(0),
    last_used_at           TIMESTAMP(0),
    created_at             TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_oauth_tokens_client ON oauth_tokens (client_id);
CREATE INDEX idx_oauth_tokens_previous_refresh ON oauth_tokens (previous_refresh_hash);

CREATE TABLE oauth_rate_hits (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket  VARCHAR(80)  NOT NULL,
    hit_at  TIMESTAMP(0) NOT NULL
);
CREATE INDEX idx_oauth_rate_hits_bucket ON oauth_rate_hits (bucket, hit_at);
