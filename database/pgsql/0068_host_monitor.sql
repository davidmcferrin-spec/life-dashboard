-- Host samples taken every five minutes. Rows older than the retention
-- setting are deleted by the collector. Readings that the hardware does
-- not expose are not stored.

CREATE TABLE host_samples (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sampled_at  TIMESTAMP(0) NOT NULL,
    metric      VARCHAR(64) NOT NULL,
    subject     VARCHAR(160) NOT NULL DEFAULT '',
    value       DOUBLE PRECISION NOT NULL,
    UNIQUE (sampled_at, metric, subject)
);

CREATE INDEX host_samples_series ON host_samples (metric, subject, sampled_at);
CREATE INDEX host_samples_sampled_at ON host_samples (sampled_at);

CREATE TABLE host_monitor_options (
    id                      SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    sample_interval_minutes INTEGER NOT NULL DEFAULT 5 CHECK (sample_interval_minutes BETWEEN 5 AND 120),
    retention_days          INTEGER NOT NULL DEFAULT 90 CHECK (retention_days BETWEEN 7 AND 365),
    hidden_sensors          JSONB NOT NULL DEFAULT '[]'::jsonb,
    tunnel_name             VARCHAR(80) NOT NULL DEFAULT '',
    tunnel_hostnames        JSONB NOT NULL DEFAULT '["https://mcp.lifeboardx.com/mcp","https://dash.lifeboardx.com"]'::jsonb,
    tunnel_metrics_url      VARCHAR(200) NOT NULL DEFAULT 'http://127.0.0.1:20241/metrics',
    tunnel_state            VARCHAR(16) NOT NULL DEFAULT '',
    updated_at              TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

