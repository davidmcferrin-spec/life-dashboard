-- Shopping lists. One user can keep several (Groceries, Costco, Hardware).
-- An open item is unique per list on the normalized name and unit, so adding
-- the same item again increases the quantity instead of inserting a second row.
-- Bought rows leave that unique set, which lets the same name be added fresh.

CREATE TABLE shopping_lists (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(80)  NOT NULL,
    sort_order INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_shopping_lists_user ON shopping_lists(user_id, sort_order, id);

CREATE TABLE shopping_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    list_id    BIGINT        NOT NULL REFERENCES shopping_lists(id) ON DELETE CASCADE,
    user_id    BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(160)  NOT NULL,
    name_key   VARCHAR(160)  NOT NULL,
    quantity   NUMERIC(12,3) NOT NULL DEFAULT 1,
    unit       VARCHAR(16),
    unit_key   VARCHAR(16)   NOT NULL DEFAULT '',
    store      VARCHAR(80),
    category   VARCHAR(24)   NOT NULL DEFAULT 'Other',
    notes      VARCHAR(500),
    added_by   VARCHAR(16)   NOT NULL DEFAULT 'user' CHECK (added_by IN ('user', 'agent')),
    bought     SMALLINT      NOT NULL DEFAULT 0 CHECK (bought IN (0, 1)),
    bought_at  TIMESTAMP(0),
    created_at TIMESTAMP(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (quantity > 0),
    CHECK (bought = 0 OR bought_at IS NOT NULL)
);
CREATE INDEX idx_shopping_items_list ON shopping_items(list_id, bought, category, name_key);
CREATE UNIQUE INDEX uq_shopping_items_open
    ON shopping_items(list_id, name_key, unit_key)
    WHERE bought = 0;

CREATE TRIGGER trg_shopping_lists_notify
    AFTER INSERT OR UPDATE OR DELETE ON shopping_lists
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_shopping_items_notify
    AFTER INSERT OR UPDATE OR DELETE ON shopping_items
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
