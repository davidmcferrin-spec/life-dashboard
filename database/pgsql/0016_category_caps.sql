-- Spending caps that take effect on a date. An older week keeps the older cap.
-- A row may set the weekly cap, the monthly cap, or both.

CREATE TABLE money_category_caps (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id    BIGINT           NOT NULL REFERENCES money_categories(id) ON DELETE CASCADE,
    weekly_cap     DOUBLE PRECISION,
    monthly_cap    DOUBLE PRECISION,
    effective_from DATE             NOT NULL,
    created_at     TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, category_id, effective_from),
    CONSTRAINT money_category_caps_value_chk CHECK (weekly_cap IS NOT NULL OR monthly_cap IS NOT NULL),
    CONSTRAINT money_category_caps_weekly_chk CHECK (weekly_cap IS NULL OR weekly_cap >= 0),
    CONSTRAINT money_category_caps_monthly_chk CHECK (monthly_cap IS NULL OR monthly_cap >= 0)
);

CREATE INDEX idx_money_category_caps_lookup
    ON money_category_caps (user_id, category_id, effective_from DESC);

CREATE TRIGGER trg_money_category_caps_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_category_caps
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
