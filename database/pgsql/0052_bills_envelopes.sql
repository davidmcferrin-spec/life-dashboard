-- Recurring bills are this cycle's payment events. Debts keep the balance and the snowball.
-- A bill may point at a debt. That link does not add the balance to cash a second time.
-- Marking a cycle paid or skipped records history only. It does not move money.
-- An envelope is a named job for dollars. A linked account balance is the funded amount.
-- The link does not transfer and does not add that balance to cash again.

CREATE TABLE money_bills (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                 VARCHAR(80)      NOT NULL,
    amount               DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (amount >= 0),
    estimated            SMALLINT         NOT NULL DEFAULT 0 CHECK (estimated IN (0, 1)),
    cadence              VARCHAR(16)      NOT NULL DEFAULT 'monthly'
                         CHECK (cadence IN ('monthly', 'biweekly', 'yearly')),
    due_day              SMALLINT         CHECK (due_day IS NULL OR due_day BETWEEN 1 AND 31),
    due_month            SMALLINT         CHECK (due_month IS NULL OR due_month BETWEEN 1 AND 12),
    anchor_on            DATE,
    pay_from_account_id  BIGINT           REFERENCES money_accounts(id) ON DELETE SET NULL,
    pay_from_label       VARCHAR(80),
    autopay              SMALLINT         NOT NULL DEFAULT 0 CHECK (autopay IN (0, 1)),
    debt_id              BIGINT           REFERENCES money_debts(id) ON DELETE SET NULL,
    category_id          BIGINT           REFERENCES money_categories(id) ON DELETE SET NULL,
    statement_min        DOUBLE PRECISION CHECK (statement_min IS NULL OR statement_min >= 0),
    default_notice       SMALLINT         NOT NULL DEFAULT 0 CHECK (default_notice IN (0, 1)),
    cancelled_charging   SMALLINT         NOT NULL DEFAULT 0 CHECK (cancelled_charging IN (0, 1)),
    notes                TEXT,
    archived_at          TIMESTAMP(0),
    created_at           TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at           TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name),
    CONSTRAINT money_bills_schedule_chk CHECK (
        (cadence = 'monthly' AND due_day IS NOT NULL)
        OR (cadence = 'yearly' AND due_day IS NOT NULL AND due_month IS NOT NULL)
        OR (cadence = 'biweekly' AND anchor_on IS NOT NULL)
    )
);
CREATE INDEX idx_money_bills_user ON money_bills (user_id, archived_at);
CREATE INDEX idx_money_bills_debt ON money_bills (debt_id);

CREATE TABLE money_bill_cycles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    bill_id       BIGINT           NOT NULL REFERENCES money_bills(id) ON DELETE CASCADE,
    cycle_due_on  DATE             NOT NULL,
    status        VARCHAR(16)      NOT NULL CHECK (status IN ('paid', 'skipped')),
    paid_on       DATE,
    amount        DOUBLE PRECISION CHECK (amount IS NULL OR amount >= 0),
    note          TEXT,
    created_at    TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (bill_id, cycle_due_on)
);
CREATE INDEX idx_money_bill_cycles_user ON money_bill_cycles (user_id, cycle_due_on);

CREATE TABLE money_envelopes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name           VARCHAR(80)      NOT NULL,
    job_type       VARCHAR(16)      NOT NULL DEFAULT 'sinking'
                   CHECK (job_type IN ('sinking', 'buffer', 'gifts', 'trip', 'escrow', 'deep_clean', 'other')),
    target_amount  DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (target_amount >= 0),
    funded_amount  DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (funded_amount >= 0),
    target_on      DATE,
    account_id     BIGINT           REFERENCES money_accounts(id) ON DELETE SET NULL,
    notes          TEXT,
    archived_at    TIMESTAMP(0),
    created_at     TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at     TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name)
);
CREATE INDEX idx_money_envelopes_user ON money_envelopes (user_id, archived_at);
CREATE UNIQUE INDEX idx_money_envelopes_account
    ON money_envelopes (user_id, account_id)
    WHERE account_id IS NOT NULL AND archived_at IS NULL;

CREATE TABLE money_payday (
    user_id          BIGINT           PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    cadence          VARCHAR(16)      NOT NULL DEFAULT 'biweekly'
                     CHECK (cadence IN ('weekly', 'biweekly', 'monthly')),
    anchor_on        DATE,
    next_on          DATE,
    paycheck_amount  DOUBLE PRECISION CHECK (paycheck_amount IS NULL OR paycheck_amount >= 0),
    living_float     DOUBLE PRECISION CHECK (living_float IS NULL OR living_float >= 0),
    updated_at       TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TRIGGER trg_money_bills_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_bills
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_bill_cycles_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_bill_cycles
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_envelopes_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_envelopes
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_payday_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_payday
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify_user();
