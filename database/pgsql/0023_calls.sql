-- Call log. Calls, a 1:1 debt-collector record, reusable vetted agencies,
-- and contacts the receptionist can match on a repeat number.
-- reference_last4 is four digits. Full account numbers and SSNs are not stored.

CREATE TABLE contacts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name           VARCHAR(160) NOT NULL,
    phones         JSONB        NOT NULL DEFAULT '[]',
    relationship   VARCHAR(80),
    vip_tier       VARCHAR(24),
    handling_rule  TEXT,
    notes          TEXT,
    created_at     TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at     TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_contacts_user ON contacts(user_id, lower(name), id);

CREATE TABLE vetted_agencies (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name          VARCHAR(160) NOT NULL,
    phones        JSONB        NOT NULL DEFAULT '[]',
    website       VARCHAR(300),
    verdict       VARCHAR(24)  NOT NULL DEFAULT 'unverified'
        CHECK (verdict IN ('unverified', 'likely_legit', 'unclear', 'suspicious', 'known_scam')),
    notes         TEXT,
    evidence_urls JSONB        NOT NULL DEFAULT '[]',
    vetted_at     TIMESTAMP(0),
    created_at    TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at    TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE UNIQUE INDEX uq_vetted_agencies_name ON vetted_agencies(user_id, lower(name));

CREATE TABLE calls (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    call_at          TIMESTAMP(0) NOT NULL,
    direction        VARCHAR(16)  NOT NULL CHECK (direction IN ('inbound', 'outbound')),
    phone            VARCHAR(20),
    callback_number  VARCHAR(20),
    name             VARCHAR(160),
    company          VARCHAR(160),
    category         VARCHAR(24)  NOT NULL DEFAULT 'personal'
        CHECK (category IN ('work', 'personal', 'vip', 'debt_collector', 'spam', 'urgent')),
    reason           VARCHAR(240),
    summary          TEXT,
    notes            TEXT,
    urgency          VARCHAR(16)  NOT NULL DEFAULT 'normal'
        CHECK (urgency IN ('low', 'normal', 'high', 'urgent')),
    deadline         DATE,
    return_needed    SMALLINT     NOT NULL DEFAULT 0 CHECK (return_needed IN (0, 1)),
    status           VARCHAR(32)  NOT NULL DEFAULT 'new'
        CHECK (status IN (
            'new', 'needs_return', 'returned', 'waiting', 'resolved',
            'spam', 'ignored', 'escalated_to_penny'
        )),
    duration_sec     INTEGER      CHECK (duration_sec IS NULL OR duration_sec >= 0),
    transcript_url   VARCHAR(500),
    recording_url    VARCHAR(500),
    transcript_text  TEXT,
    has_recording    SMALLINT     NOT NULL DEFAULT 0 CHECK (has_recording IN (0, 1)),
    source           VARCHAR(16)  NOT NULL DEFAULT 'manual'
        CHECK (source IN ('ai', 'manual', 'bland')),
    source_call_id   VARCHAR(128),
    linked_todo_id   BIGINT       REFERENCES user_todo_items(id) ON DELETE SET NULL,
    contact_id       BIGINT       REFERENCES contacts(id) ON DELETE SET NULL,
    handled_by       VARCHAR(16)  CHECK (handled_by IS NULL OR handled_by IN ('claire', 'cos', 'david')),
    notified_david   SMALLINT     NOT NULL DEFAULT 0 CHECK (notified_david IN (0, 1)),
    notified_at      TIMESTAMP(0),
    created_at       TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at       TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_calls_user_time ON calls(user_id, call_at DESC, id DESC);
CREATE INDEX idx_calls_user_status ON calls(user_id, status, return_needed);
CREATE UNIQUE INDEX uq_calls_source_call
    ON calls(user_id, source_call_id)
    WHERE source_call_id IS NOT NULL;

CREATE TABLE call_debt (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id               BIGINT NOT NULL UNIQUE REFERENCES calls(id) ON DELETE CASCADE,
    user_id               BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    collector_name        VARCHAR(160),
    agency                VARCHAR(160),
    agency_address        VARCHAR(300),
    agency_phone          VARCHAR(20),
    website               VARCHAR(300),
    original_creditor     VARCHAR(160),
    reference_last4       VARCHAR(4)    CHECK (reference_last4 IS NULL OR reference_last4 ~ '^[0-9]{4}$'),
    amount_claimed        NUMERIC(14,2) CHECK (amount_claimed IS NULL OR amount_claimed >= 0),
    debt_date             DATE,
    validation_requested  SMALLINT      NOT NULL DEFAULT 0 CHECK (validation_requested IN (0, 1)),
    verdict               VARCHAR(24)   NOT NULL DEFAULT 'unverified'
        CHECK (verdict IN ('unverified', 'likely_legit', 'unclear', 'suspicious', 'known_scam')),
    scam_reasons          TEXT,
    verification_notes    TEXT,
    cfpb_complaints       TEXT,
    state_license         VARCHAR(80),
    ag_ftc_warnings       TEXT,
    evidence_urls         JSONB         NOT NULL DEFAULT '[]',
    vetted_at             TIMESTAMP(0),
    referred_to_penny     SMALLINT      NOT NULL DEFAULT 0 CHECK (referred_to_penny IN (0, 1))
);
CREATE INDEX idx_call_debt_user ON call_debt(user_id, call_id);

CREATE TRIGGER trg_contacts_notify
    AFTER INSERT OR UPDATE OR DELETE ON contacts
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_vetted_agencies_notify
    AFTER INSERT OR UPDATE OR DELETE ON vetted_agencies
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_calls_notify
    AFTER INSERT OR UPDATE OR DELETE ON calls
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_call_debt_notify
    AFTER INSERT OR UPDATE OR DELETE ON call_debt
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
