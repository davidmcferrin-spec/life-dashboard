-- Per-track mixtape notes and the season windows that gate them.
-- Spotify audio-features is unavailable, so these values are entered here.
-- lifedash_notify() reads id and user_id.

CREATE TABLE spotify_track_meta (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    spotify_track_id  VARCHAR(64)  NOT NULL,
    bpm               NUMERIC(6,2),
    musical_key       VARCHAR(32),
    camelot           VARCHAR(3),
    energy            SMALLINT CHECK (energy IS NULL OR energy BETWEEN 1 AND 10),
    mood_tags         JSONB        NOT NULL DEFAULT '[]'::jsonb,
    season_tags       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    source            VARCHAR(16)  NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'estimated')),
    updated_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, spotify_track_id)
);
CREATE INDEX idx_spotify_track_meta_user ON spotify_track_meta(user_id, updated_at DESC);

CREATE TABLE spotify_season_windows (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    season        VARCHAR(32)  NOT NULL,
    start_anchor  VARCHAR(16)  NOT NULL DEFAULT '',
    start_month   SMALLINT CHECK (start_month IS NULL OR start_month BETWEEN 1 AND 12),
    start_day     SMALLINT CHECK (start_day IS NULL OR start_day BETWEEN 1 AND 31),
    end_month     SMALLINT     NOT NULL CHECK (end_month BETWEEN 1 AND 12),
    end_day       SMALLINT     NOT NULL CHECK (end_day BETWEEN 1 AND 31),
    updated_at    TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, season)
);

ALTER TABLE spotify_prompts
    ADD COLUMN theme TEXT,
    ADD COLUMN arc JSONB NOT NULL DEFAULT '{}'::jsonb,
    ADD COLUMN season_tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN allow_seasons JSONB NOT NULL DEFAULT '[]'::jsonb;

INSERT INTO spotify_season_windows (user_id, season, start_anchor, end_month, end_day)
SELECT id, season, 'thanksgiving', 1, 6
FROM users
CROSS JOIN (VALUES ('christmas'), ('holiday')) AS names(season);

CREATE TRIGGER trg_spotify_track_meta_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_track_meta
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_spotify_season_windows_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_season_windows
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
