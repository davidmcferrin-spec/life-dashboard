-- Playlist-page ratings. Spotify has no public dislike endpoint,
-- so a thumbs down stays in this database.
-- playlist_id is cleared when the playlist row goes away; the track URI stays.

CREATE TABLE spotify_track_ratings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    playlist_id  BIGINT       REFERENCES spotify_playlists(id) ON DELETE SET NULL,
    track_uri    VARCHAR(80)  NOT NULL,
    rating       VARCHAR(8)   NOT NULL CHECK (rating IN ('up', 'down')),
    source       VARCHAR(16)  NOT NULL DEFAULT 'user' CHECK (source = 'user'),
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_spotify_track_ratings_user ON spotify_track_ratings (user_id, id DESC);
CREATE INDEX idx_spotify_track_ratings_playlist ON spotify_track_ratings (user_id, playlist_id, id DESC);

-- Current do-not-use set. The ratings table keeps every event.
-- A later thumbs up removes the row.
CREATE TABLE spotify_disliked_tracks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    track_uri    VARCHAR(80)  NOT NULL,
    name         TEXT,
    artists      JSONB        NOT NULL DEFAULT '[]'::jsonb,
    playlist_id  BIGINT       REFERENCES spotify_playlists(id) ON DELETE SET NULL,
    source       VARCHAR(16)  NOT NULL DEFAULT 'user' CHECK (source = 'user'),
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, track_uri),
    CONSTRAINT spotify_disliked_tracks_artists_array CHECK (jsonb_typeof(artists) = 'array')
);
CREATE INDEX idx_spotify_disliked_tracks_user ON spotify_disliked_tracks (user_id, id DESC);

CREATE TRIGGER trg_spotify_track_ratings_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_track_ratings
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_spotify_disliked_tracks_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_disliked_tracks
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
