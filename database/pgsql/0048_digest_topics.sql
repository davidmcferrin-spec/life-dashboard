-- Labels on digest entries. A chip is a topic that tags at least one entry.

CREATE TABLE digest_topics (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    slug       VARCHAR(40)  NOT NULL,
    label      VARCHAR(40)  NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, slug)
);

CREATE TABLE digest_entry_topics (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entry_id BIGINT NOT NULL REFERENCES digest_entries(id) ON DELETE CASCADE,
    topic_id BIGINT NOT NULL REFERENCES digest_topics(id) ON DELETE CASCADE,
    UNIQUE (entry_id, topic_id)
);

CREATE INDEX idx_digest_entry_topics_topic ON digest_entry_topics (topic_id);

CREATE TRIGGER trg_digest_topics_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_topics
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_digest_entry_topics_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_entry_topics
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
