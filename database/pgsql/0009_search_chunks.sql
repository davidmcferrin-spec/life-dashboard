-- One text index for every dataset the dashboard stores.
-- "Apple" is a literal match against title and body. Embeddings are optional
-- and never required for that match.

CREATE TABLE search_chunks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dataset      VARCHAR(32)  NOT NULL,
    source_id    VARCHAR(64)  NOT NULL,
    title        VARCHAR(300) NOT NULL,
    body         TEXT         NOT NULL,
    url          TEXT,
    content_hash VARCHAR(64)  NOT NULL,
    embedding    JSONB,
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dataset, source_id)
);
CREATE INDEX idx_search_chunks_user ON search_chunks(user_id, dataset);
