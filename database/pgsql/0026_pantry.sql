-- Pantry lots, the product catalog, and recipes.
-- Shelf-life numbers are per user so Settings can edit them.
-- category_shelf_life is the fallback when a product's own days are null.

CREATE TABLE category_shelf_life (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category     VARCHAR(24)  NOT NULL,
    pantry_days  INTEGER      CHECK (pantry_days IS NULL OR pantry_days >= 0),
    fridge_days  INTEGER      CHECK (fridge_days IS NULL OR fridge_days >= 0),
    freezer_days INTEGER      CHECK (freezer_days IS NULL OR freezer_days >= 0),
    opened_days  INTEGER      CHECK (opened_days IS NULL OR opened_days >= 0),
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, category)
);

CREATE TABLE pantry_products (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    upc                     VARCHAR(14),
    name                    VARCHAR(200) NOT NULL,
    name_key                VARCHAR(200) NOT NULL,
    brand                   VARCHAR(120),
    category                VARCHAR(24)  NOT NULL,
    default_size            VARCHAR(80),
    default_unit            VARCHAR(16),
    shelf_life_pantry_days  INTEGER      CHECK (shelf_life_pantry_days IS NULL OR shelf_life_pantry_days >= 0),
    shelf_life_fridge_days  INTEGER      CHECK (shelf_life_fridge_days IS NULL OR shelf_life_fridge_days >= 0),
    shelf_life_freezer_days INTEGER      CHECK (shelf_life_freezer_days IS NULL OR shelf_life_freezer_days >= 0),
    opened_life_days        INTEGER      CHECK (opened_life_days IS NULL OR opened_life_days >= 0),
    min_on_hand             NUMERIC(12,3) CHECK (min_on_hand IS NULL OR min_on_hand >= 0),
    image_url               VARCHAR(500),
    notes                   TEXT,
    source                  VARCHAR(16)  NOT NULL DEFAULT 'manual'
                            CHECK (source IN ('manual', 'vault', 'lookup', 'order', 'produce')),
    created_at              TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at              TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE UNIQUE INDEX uq_pantry_products_upc
    ON pantry_products(user_id, upc) WHERE upc IS NOT NULL;
CREATE INDEX idx_pantry_products_name ON pantry_products(user_id, name_key);

CREATE TABLE pantry_lots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id        BIGINT        NOT NULL REFERENCES pantry_products(id) ON DELETE RESTRICT,
    quantity          NUMERIC(12,3) NOT NULL CHECK (quantity >= 0),
    unit              VARCHAR(16)   NOT NULL,
    qty_level         VARCHAR(16)   CHECK (qty_level IS NULL OR qty_level IN ('full', 'most', 'half', 'low', 'nearly_empty')),
    location          VARCHAR(16)   NOT NULL CHECK (location IN ('pantry', 'fridge', 'freezer')),
    purchased_at      DATE          NOT NULL,
    store             VARCHAR(80),
    order_ref         VARCHAR(80),
    unit_price        NUMERIC(12,2) CHECK (unit_price IS NULL OR unit_price >= 0),
    use_by            DATE,
    use_by_overridden SMALLINT      NOT NULL DEFAULT 0 CHECK (use_by_overridden IN (0, 1)),
    opened_at         TIMESTAMP(0),
    status            VARCHAR(16)   NOT NULL DEFAULT 'on_hand'
                      CHECK (status IN ('on_hand', 'used', 'tossed', 'expired')),
    parent_lot_id     BIGINT        REFERENCES pantry_lots(id) ON DELETE SET NULL,
    created_at        TIMESTAMP(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at        TIMESTAMP(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (status <> 'on_hand' OR quantity > 0)
);
CREATE INDEX idx_pantry_lots_open
    ON pantry_lots(user_id, status, location, use_by);
CREATE INDEX idx_pantry_lots_product
    ON pantry_lots(user_id, product_id, status, use_by);

CREATE TABLE pantry_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lot_id     BIGINT        NOT NULL REFERENCES pantry_lots(id) ON DELETE CASCADE,
    action     VARCHAR(16)   NOT NULL CHECK (action IN ('add', 'consume', 'split', 'move', 'open', 'toss', 'adjust')),
    quantity   NUMERIC(12,3) NOT NULL CHECK (quantity >= 0),
    at         TIMESTAMP(0)  NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    by_name    VARCHAR(64)   NOT NULL,
    note       VARCHAR(500)
);
CREATE INDEX idx_pantry_events_lot ON pantry_events(lot_id, id);
CREATE INDEX idx_pantry_events_user_at ON pantry_events(user_id, at);

CREATE TABLE pantry_recipes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(160) NOT NULL,
    notes      TEXT,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_pantry_recipes_user ON pantry_recipes(user_id, name);

CREATE TABLE pantry_recipe_ingredients (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT        NOT NULL REFERENCES pantry_recipes(id) ON DELETE CASCADE,
    user_id    BIGINT        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    product_id BIGINT        REFERENCES pantry_products(id) ON DELETE CASCADE,
    category   VARCHAR(24),
    quantity   NUMERIC(12,3) CHECK (quantity IS NULL OR quantity > 0),
    unit       VARCHAR(16),
    CHECK (product_id IS NOT NULL OR category IS NOT NULL)
);
CREATE INDEX idx_pantry_recipe_ingredients_recipe ON pantry_recipe_ingredients(recipe_id);

-- Shared across users. A miss is cached so a scan does not hammer the lookup hosts.
CREATE TABLE pantry_lookup_cache (
    upc        VARCHAR(14) PRIMARY KEY,
    found      SMALLINT    NOT NULL CHECK (found IN (0, 1)),
    name       VARCHAR(200),
    brand      VARCHAR(120),
    size       VARCHAR(80),
    image_url  VARCHAR(500),
    source     VARCHAR(32),
    fetched_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TRIGGER trg_pantry_products_notify
    AFTER INSERT OR UPDATE OR DELETE ON pantry_products
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_pantry_lots_notify
    AFTER INSERT OR UPDATE OR DELETE ON pantry_lots
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
