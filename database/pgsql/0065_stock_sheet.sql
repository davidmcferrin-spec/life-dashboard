-- Quotes and play-account buys copied from a Google Sheet.
-- The sheet is the source of truth and is never written back to.
-- Symbol (or date + ticker) is the identity so a reorder updates the same row.

CREATE TABLE stock_sheet_quotes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sheet               VARCHAR(16) NOT NULL CHECK (sheet IN ('watchlist', 'commodity')),
    role                VARCHAR(40),
    exchange            VARCHAR(40),
    symbol              VARCHAR(32) NOT NULL,
    name                VARCHAR(200),
    proxy_for           VARCHAR(120),
    price               DOUBLE PRECISION,
    open_price          DOUBLE PRECISION,
    high_price          DOUBLE PRECISION,
    low_price           DOUBLE PRECISION,
    change_amount       DOUBLE PRECISION,
    change_pct          DOUBLE PRECISION,
    prev_close          DOUBLE PRECISION,
    high_52w            DOUBLE PRECISION,
    low_52w             DOUBLE PRECISION,
    pct_off_52w         DOUBLE PRECISION,
    volume              DOUBLE PRECISION,
    avg_volume          DOUBLE PRECISION,
    market_cap          DOUBLE PRECISION,
    pe                  DOUBLE PRECISION,
    eps                 DOUBLE PRECISION,
    beta                DOUBLE PRECISION,
    shares_outstanding  DOUBLE PRECISION,
    currency            VARCHAR(12),
    thesis              TEXT,
    last_reviewed       DATE,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, sheet, symbol)
);
CREATE INDEX idx_stock_sheet_quotes_user ON stock_sheet_quotes (user_id, sheet, sort_order);

CREATE TABLE stock_play_trades (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    trade_date  DATE NOT NULL,
    ticker      VARCHAR(32) NOT NULL,
    amount      DOUBLE PRECISION,
    shares      DOUBLE PRECISION,
    price       DOUBLE PRECISION,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, trade_date, ticker)
);
CREATE INDEX idx_stock_play_trades_user ON stock_play_trades (user_id, sort_order);

CREATE TABLE stock_sheet_sync (
    user_id           BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    status            VARCHAR(16) NOT NULL DEFAULT 'never'
                      CHECK (status IN ('never', 'ok', 'error')),
    sync_error        TEXT,
    last_synced_at    TIMESTAMP(0),
    last_attempt_at   TIMESTAMP(0),
    watchlist_count   INTEGER NOT NULL DEFAULT 0,
    commodity_count   INTEGER NOT NULL DEFAULT 0,
    play_count        INTEGER NOT NULL DEFAULT 0,
    updated_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TRIGGER trg_stock_sheet_quotes_notify
    AFTER INSERT OR UPDATE OR DELETE ON stock_sheet_quotes
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_stock_play_trades_notify
    AFTER INSERT OR UPDATE OR DELETE ON stock_play_trades
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

-- user_id is the key, and lifedash_notify() reads id.
CREATE TRIGGER trg_stock_sheet_sync_notify
    AFTER INSERT OR UPDATE OR DELETE ON stock_sheet_sync
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify_user();
