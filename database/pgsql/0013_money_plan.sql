-- Budget, debts, sinking funds, Baby Steps, credit history, and retirement inputs.
-- Extends the L5 money tables. Full account numbers are not a column.
-- last4 is four digits or null. One subscription is stored only as "Creator subscription".

ALTER TABLE money_accounts
    ADD COLUMN institution VARCHAR(80),
    ADD COLUMN last4 CHAR(4),
    ADD COLUMN credit_limit DOUBLE PRECISION;

ALTER TABLE money_accounts
    ADD CONSTRAINT money_accounts_last4_chk CHECK (last4 IS NULL OR last4 ~ '^[0-9]{4}$'),
    ADD CONSTRAINT money_accounts_limit_chk CHECK (credit_limit IS NULL OR credit_limit >= 0);

CREATE TABLE money_categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(80)      NOT NULL,
    kind        VARCHAR(16)      NOT NULL DEFAULT 'expense'
                CHECK (kind IN ('income', 'expense', 'transfer')),
    weekly_cap  DOUBLE PRECISION,
    archived_at TIMESTAMP(0),
    created_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name)
);
CREATE INDEX idx_money_categories_user ON money_categories (user_id);

ALTER TABLE money_transactions
    ADD COLUMN category_id BIGINT REFERENCES money_categories(id) ON DELETE SET NULL;
CREATE INDEX idx_money_tx_category ON money_transactions (user_id, category_id);

CREATE TABLE money_budget_lines (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    year        SMALLINT         NOT NULL,
    month       SMALLINT         NOT NULL CHECK (month BETWEEN 1 AND 12),
    category_id BIGINT           NOT NULL REFERENCES money_categories(id) ON DELETE CASCADE,
    amount      DOUBLE PRECISION NOT NULL CHECK (amount >= 0),
    due_day     SMALLINT         CHECK (due_day IS NULL OR due_day BETWEEN 1 AND 31),
    UNIQUE (user_id, year, month, category_id)
);
CREATE INDEX idx_money_budget_month ON money_budget_lines (user_id, year, month);

CREATE TABLE money_debts (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id        BIGINT           REFERENCES money_accounts(id) ON DELETE SET NULL,
    name              VARCHAR(80)      NOT NULL,
    last4             CHAR(4),
    balance           DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (balance >= 0),
    apr_percent       DOUBLE PRECISION NOT NULL DEFAULT 0,
    minimum_payment   DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (minimum_payment >= 0),
    payoff_order      SMALLINT         NOT NULL DEFAULT 1,
    target_payoff_on  DATE,
    due_day           SMALLINT         CHECK (due_day IS NULL OR due_day BETWEEN 1 AND 31),
    archived_at       TIMESTAMP(0),
    updated_at        TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name),
    CONSTRAINT money_debts_last4_chk CHECK (last4 IS NULL OR last4 ~ '^[0-9]{4}$')
);
CREATE INDEX idx_money_debts_order ON money_debts (user_id, payoff_order);

CREATE TABLE money_sinking_funds (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name          VARCHAR(80)      NOT NULL,
    target_amount DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (target_amount >= 0),
    balance       DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (balance >= 0),
    due_on        DATE,
    archived_at   TIMESTAMP(0),
    updated_at    TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name)
);
CREATE INDEX idx_money_sinking_due ON money_sinking_funds (user_id, due_on);

ALTER TABLE money_snapshots
    ADD COLUMN breakdown JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE TABLE money_baby_steps (
    user_id    BIGINT       PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    step       SMALLINT     NOT NULL CHECK (step BETWEEN 1 AND 7),
    note       TEXT,
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE money_credit_scores (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    as_of                DATE             NOT NULL,
    score                SMALLINT         NOT NULL CHECK (score BETWEEN 300 AND 850),
    utilization_percent  DOUBLE PRECISION,
    UNIQUE (user_id, as_of)
);
CREATE INDEX idx_money_credit_user ON money_credit_scores (user_id, as_of DESC);

CREATE TABLE money_retirement (
    user_id              BIGINT           PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    contribution_rate    DOUBLE PRECISION,
    annual_income        DOUBLE PRECISION,
    employer_match_rate  DOUBLE PRECISION,
    updated_at           TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- Baby Steps and retirement use user_id as the key, so they cannot call
-- lifedash_notify() (that function reads rec.id).
CREATE FUNCTION lifedash_notify_user() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    rec     RECORD;
    payload JSONB;
BEGIN
    IF TG_OP = 'DELETE' THEN
        rec := OLD;
    ELSE
        rec := NEW;
    END IF;
    payload := jsonb_build_object(
        'table',   TG_TABLE_NAME,
        'op',      lower(TG_OP),
        'id',      rec.user_id,
        'user_id', rec.user_id
    );
    PERFORM pg_notify('lifedash_events', payload::text);
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_money_categories_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_categories
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_budget_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_budget_lines
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_debts_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_debts
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_sinking_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_sinking_funds
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_snapshots_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_snapshots
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_credit_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_credit_scores
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_baby_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_baby_steps
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify_user();

CREATE TRIGGER trg_money_retirement_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_retirement
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify_user();
