-- Briefs, trips, a dial-bot contact book, a video slate, and research findings.
-- trip_id sits on the rows a trip already lives next to. A matching tag or
-- order_wave is the other link, so those tables do not need a second scheme.

CREATE TABLE digests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source      VARCHAR(80)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    digest_date DATE         NOT NULL,
    items       JSONB        NOT NULL DEFAULT '[]',
    page_id     BIGINT       REFERENCES pages(id) ON DELETE SET NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_digests_user_date ON digests (user_id, digest_date DESC, id DESC);
CREATE UNIQUE INDEX uq_digests_brief ON digests (user_id, lower(source), digest_date, lower(title));

CREATE TABLE trips (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(200) NOT NULL,
    destination VARCHAR(200) NOT NULL DEFAULT '',
    start_date  DATE,
    end_date    DATE,
    status      VARCHAR(16)  NOT NULL DEFAULT 'idea'
                CHECK (status IN ('idea', 'planning', 'booked', 'done')),
    owner_bot   VARCHAR(80),
    tags        TEXT[]       NOT NULL DEFAULT '{}',
    folder_id   BIGINT       REFERENCES page_folders(id) ON DELETE SET NULL,
    page_id     BIGINT       REFERENCES pages(id) ON DELETE SET NULL,
    notes       TEXT         NOT NULL DEFAULT '',
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_trips_user_start ON trips (user_id, start_date, id);

ALTER TABLE pages ADD COLUMN trip_id BIGINT REFERENCES trips(id) ON DELETE SET NULL;
CREATE INDEX idx_pages_trip ON pages (user_id, trip_id) WHERE trip_id IS NOT NULL;

ALTER TABLE shopping_items ADD COLUMN trip_id BIGINT REFERENCES trips(id) ON DELETE SET NULL;
CREATE INDEX idx_shopping_items_trip ON shopping_items (user_id, trip_id) WHERE trip_id IS NOT NULL;

ALTER TABLE handoffs ADD COLUMN trip_id BIGINT REFERENCES trips(id) ON DELETE SET NULL;
CREATE INDEX idx_handoffs_trip ON handoffs (user_id, trip_id) WHERE trip_id IS NOT NULL;

ALTER TABLE calls ADD COLUMN to_number VARCHAR(20);
ALTER TABLE calls ADD COLUMN from_number VARCHAR(20);
ALTER TABLE calls ADD COLUMN purpose VARCHAR(240);
ALTER TABLE calls ADD COLUMN started_at TIMESTAMP(0);
ALTER TABLE calls ADD COLUMN outcome VARCHAR(80);
ALTER TABLE calls ADD COLUMN placed_by VARCHAR(80);

ALTER TABLE contacts ADD COLUMN emails JSONB NOT NULL DEFAULT '[]';
ALTER TABLE contacts ADD COLUMN org VARCHAR(160);
ALTER TABLE contacts ADD COLUMN tags TEXT[] NOT NULL DEFAULT '{}';

CREATE TABLE video_slate (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    channel     VARCHAR(120) NOT NULL,
    title       VARCHAR(200) NOT NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'idea'
                CHECK (status IN ('idea', 'scripted', 'voiced', 'edited', 'scheduled', 'published')),
    target_date DATE,
    publish_url VARCHAR(500),
    notes       TEXT         NOT NULL DEFAULT '',
    tags        TEXT[]       NOT NULL DEFAULT '{}',
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_video_slate_user ON video_slate (user_id, status, target_date, id);

CREATE TABLE research_findings (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    topic      VARCHAR(120) NOT NULL,
    source_bot VARCHAR(80)  NOT NULL,
    title      VARCHAR(200) NOT NULL,
    summary    TEXT         NOT NULL DEFAULT '',
    url        VARCHAR(500),
    found_at   TIMESTAMP(0) NOT NULL,
    tags       TEXT[]       NOT NULL DEFAULT '{}',
    page_id    BIGINT       REFERENCES pages(id) ON DELETE SET NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_findings_user_topic ON research_findings (user_id, topic, found_at DESC, id DESC);
