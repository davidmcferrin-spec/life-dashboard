-- A meal log is a record of what was eaten. It is separate from health_points
-- meal notes so a row can carry a meal type, a place, and a cost.
-- Blood pressure, medicines, and appointments are personal logs, not device samples.

CREATE TABLE meal_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT         NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    eaten_on    DATE           NOT NULL,
    meal_type   VARCHAR(16)    NOT NULL CHECK (meal_type IN ('breakfast', 'lunch', 'dinner', 'snack', 'other')),
    description TEXT           NOT NULL,
    items       JSONB          NOT NULL DEFAULT '[]'::jsonb,
    eaten_out   BOOLEAN        NOT NULL DEFAULT FALSE,
    place       VARCHAR(160),
    cost        NUMERIC(10, 2) CHECK (cost IS NULL OR cost >= 0),
    created_at  TIMESTAMP(0)   NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_meal_logs_user_day ON meal_logs (user_id, eaten_on DESC, id DESC);

CREATE TABLE blood_pressure_readings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    systolic    SMALLINT     NOT NULL CHECK (systolic BETWEEN 50 AND 300),
    diastolic   SMALLINT     NOT NULL CHECK (diastolic BETWEEN 30 AND 200),
    pulse       SMALLINT     CHECK (pulse IS NULL OR pulse BETWEEN 20 AND 250),
    taken_at    TIMESTAMP(0) NOT NULL,
    arm         VARCHAR(16)  CHECK (arm IS NULL OR arm IN ('left', 'right')),
    position    VARCHAR(16)  CHECK (position IS NULL OR position IN ('sitting', 'standing', 'lying')),
    notes       TEXT,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (systolic > diastolic)
);
CREATE INDEX idx_bp_user_taken ON blood_pressure_readings (user_id, taken_at DESC);

CREATE TABLE medications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(160) NOT NULL,
    dose        VARCHAR(80),
    schedule    VARCHAR(160),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    started_on  DATE,
    stopped_on  DATE,
    notes       TEXT,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (stopped_on IS NULL OR started_on IS NULL OR stopped_on >= started_on)
);
CREATE INDEX idx_medications_user_active ON medications (user_id, active, name);

CREATE TABLE medication_doses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    medication_id   BIGINT       NOT NULL REFERENCES medications(id) ON DELETE CASCADE,
    taken_at        TIMESTAMP(0) NOT NULL,
    notes           TEXT,
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_medication_doses_user ON medication_doses (user_id, medication_id, taken_at DESC);

CREATE TABLE appointments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    provider    VARCHAR(160) NOT NULL,
    specialty   VARCHAR(80),
    starts_at   TIMESTAMP(0) NOT NULL,
    location    VARCHAR(200),
    reason      TEXT,
    status      VARCHAR(16)  NOT NULL DEFAULT 'scheduled'
                CHECK (status IN ('scheduled', 'completed', 'cancelled', 'missed')),
    follow_up   TEXT,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_appointments_user_start ON appointments (user_id, starts_at);
