-- Spotify library, staged playlist edits, and play history.
-- lifedash_notify() reads id and user_id, so every table has both.
-- Play history is unique per dashboard user: the same track can play at the
-- same second on two accounts. Playlist tracks are not unique: Spotify allows
-- the same track twice.

CREATE TABLE spotify_account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    spotify_user_id     VARCHAR(64)  NOT NULL,
    display_name        TEXT         NOT NULL,
    access_token_enc    TEXT         NOT NULL,
    refresh_token_enc   TEXT         NOT NULL,
    expires_at          TIMESTAMP(0),
    scopes              TEXT         NOT NULL DEFAULT '',
    status              VARCHAR(16)  NOT NULL DEFAULT 'connected' CHECK (status IN ('connected', 'needs_reauth')),
    status_detail       TEXT,
    last_sync_at        TIMESTAMP(0),
    last_sync_status    VARCHAR(16),
    last_sync_error     TEXT,
    created_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE spotify_prompts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name                VARCHAR(120) NOT NULL,
    prompt              TEXT         NOT NULL,
    target_playlist_id  BIGINT,
    refresh_schedule    VARCHAR(32),
    last_run_at         TIMESTAMP(0),
    notes               TEXT,
    active              SMALLINT     NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_spotify_prompts_user ON spotify_prompts(user_id, name);

CREATE TABLE spotify_playlists (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    spotify_id          VARCHAR(64),
    name                TEXT         NOT NULL,
    description         TEXT         NOT NULL DEFAULT '',
    is_public           SMALLINT     NOT NULL DEFAULT 0 CHECK (is_public IN (0, 1)),
    collaborative       SMALLINT     NOT NULL DEFAULT 0 CHECK (collaborative IN (0, 1)),
    owner_id            VARCHAR(64),
    owner_name          TEXT,
    snapshot_id         TEXT,
    track_count         INTEGER      NOT NULL DEFAULT 0,
    image_url           TEXT,
    last_synced_at      TIMESTAMP(0),
    local_dirty         SMALLINT     NOT NULL DEFAULT 0 CHECK (local_dirty IN (0, 1)),
    managed_by_ai       SMALLINT     NOT NULL DEFAULT 0 CHECK (managed_by_ai IN (0, 1)),
    source_prompt_id    BIGINT,
    created_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE UNIQUE INDEX idx_spotify_playlists_remote ON spotify_playlists(user_id, spotify_id) WHERE spotify_id IS NOT NULL;
CREATE INDEX idx_spotify_playlists_user ON spotify_playlists(user_id, name);

CREATE TABLE spotify_tracks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    spotify_id          VARCHAR(64)  NOT NULL,
    name                TEXT         NOT NULL,
    artists             JSONB        NOT NULL DEFAULT '[]'::jsonb,
    album               TEXT,
    duration_ms         INTEGER      NOT NULL DEFAULT 0,
    explicit            SMALLINT     NOT NULL DEFAULT 0 CHECK (explicit IN (0, 1)),
    popularity          SMALLINT,
    isrc                VARCHAR(32),
    image_url           TEXT,
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, spotify_id)
);
CREATE INDEX idx_spotify_tracks_user ON spotify_tracks(user_id, name);

CREATE TABLE spotify_playlist_tracks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    playlist_id         BIGINT       NOT NULL REFERENCES spotify_playlists(id) ON DELETE CASCADE,
    track_id            BIGINT       NOT NULL REFERENCES spotify_tracks(id) ON DELETE CASCADE,
    position            INTEGER      NOT NULL,
    added_at            TIMESTAMP(0),
    added_by            VARCHAR(64)
);
CREATE INDEX idx_spotify_playlist_tracks_pos ON spotify_playlist_tracks(playlist_id, position);

CREATE TABLE spotify_playlist_changes (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    playlist_id         BIGINT       NOT NULL REFERENCES spotify_playlists(id) ON DELETE CASCADE,
    op                  VARCHAR(16)  NOT NULL CHECK (op IN ('add', 'remove', 'reorder', 'rename', 'describe', 'create', 'delete')),
    payload             JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_by          VARCHAR(16)  NOT NULL CHECK (created_by IN ('david', 'mcp', 'ai')),
    status              VARCHAR(16)  NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'pushed', 'failed', 'discarded')),
    error               TEXT,
    created_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_spotify_playlist_changes_open ON spotify_playlist_changes(playlist_id, status, id);

CREATE TABLE spotify_play_history (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    track_id            BIGINT       NOT NULL REFERENCES spotify_tracks(id) ON DELETE CASCADE,
    played_at           TIMESTAMP(0) NOT NULL,
    context_uri         TEXT,
    UNIQUE (user_id, track_id, played_at)
);
CREATE INDEX idx_spotify_play_history_user ON spotify_play_history(user_id, played_at DESC);

CREATE TABLE spotify_saved_tracks (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    track_id            BIGINT       NOT NULL REFERENCES spotify_tracks(id) ON DELETE CASCADE,
    added_at            TIMESTAMP(0) NOT NULL,
    UNIQUE (user_id, track_id)
);
CREATE INDEX idx_spotify_saved_tracks_user ON spotify_saved_tracks(user_id, added_at DESC);

CREATE TABLE spotify_top_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind                VARCHAR(16)  NOT NULL CHECK (kind IN ('artist', 'track')),
    time_range          VARCHAR(16)  NOT NULL CHECK (time_range IN ('short_term', 'medium_term', 'long_term')),
    rank                SMALLINT     NOT NULL,
    spotify_id          VARCHAR(64)  NOT NULL,
    name                TEXT         NOT NULL,
    payload             JSONB        NOT NULL DEFAULT '{}'::jsonb,
    refreshed_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, kind, time_range, rank)
);
CREATE INDEX idx_spotify_top_items_user ON spotify_top_items(user_id, kind, time_range);

CREATE TABLE spotify_taste_profile (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    body                JSONB        NOT NULL DEFAULT '{}'::jsonb,
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE spotify_sync_log (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind                VARCHAR(16)  NOT NULL,
    started_at          TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    finished_at         TIMESTAMP(0),
    status              VARCHAR(16)  NOT NULL,
    counts              JSONB        NOT NULL DEFAULT '{}'::jsonb,
    error               TEXT
);
CREATE INDEX idx_spotify_sync_log_user ON spotify_sync_log(user_id, started_at DESC);

CREATE TRIGGER trg_spotify_account_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_account
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

