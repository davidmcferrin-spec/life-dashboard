-- Setup wizard profile, routine switches, privacy choices, and one run per routine per day.

CREATE TABLE jarvis_profiles (
    user_id         BIGINT       PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    display_name    VARCHAR(80)  NOT NULL,
    assistant_name  VARCHAR(40)  NOT NULL,
    style           VARCHAR(20)  NOT NULL CHECK (style IN ('concise', 'conversational', 'analytical')),
    voice_profile   VARCHAR(16)  NOT NULL DEFAULT '' CHECK (voice_profile IN ('', 'atlas', 'nova', 'orion')),
    initialized_at  TIMESTAMP(0),
    updated_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE jarvis_routines (
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    routine_key  VARCHAR(32)  NOT NULL CHECK (routine_key IN ('morning_brief', 'meeting_prep', 'focus_mode', 'day_summary')),
    enabled      SMALLINT     NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
    mode         VARCHAR(16)  NOT NULL CHECK (mode IN ('automatic', 'triggered')),
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    PRIMARY KEY (user_id, routine_key)
);

CREATE TABLE jarvis_privacy (
    user_id           BIGINT      PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    calendar_context  VARCHAR(16) NOT NULL CHECK (calendar_context IN ('off', 'allowed')),
    microphone        VARCHAR(16) NOT NULL CHECK (microphone IN ('off', 'while_active')),
    memory            VARCHAR(16) NOT NULL CHECK (memory IN ('off', 'review', 'allowed')),
    proactive         VARCHAR(16) NOT NULL CHECK (proactive IN ('ask', 'allowed')),
    updated_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE jarvis_routine_runs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    routine_key  VARCHAR(32)  NOT NULL,
    local_date   DATE         NOT NULL,
    status       VARCHAR(16)  NOT NULL CHECK (status IN ('ran', 'waiting')),
    summary      TEXT         NOT NULL DEFAULT '',
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, routine_key, local_date)
);
