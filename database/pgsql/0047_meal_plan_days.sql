-- One lunch and one dinner per person per weekday. The planner shows Monday through Friday.

CREATE TABLE meal_plan_days (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    plan_date  DATE        NOT NULL,
    slot       VARCHAR(8)  NOT NULL CHECK (slot IN ('lunch', 'dinner')),
    title      VARCHAR(160) NOT NULL,
    detail     VARCHAR(240),
    recipe_id  BIGINT      REFERENCES pantry_recipes(id) ON DELETE SET NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT meal_plan_days_weekday CHECK (EXTRACT(ISODOW FROM plan_date) BETWEEN 1 AND 5),
    CONSTRAINT meal_plan_days_user_date_slot UNIQUE (user_id, plan_date, slot)
);

-- The open meals page refreshes when a day changes.
CREATE TRIGGER trg_meal_plan_days_notify
    AFTER INSERT OR UPDATE OR DELETE ON meal_plan_days
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
