-- Version keys for range compare, and one normalized snapshot per source per day.
-- Retention is the user preference digest_snapshot_days (default 180).

ALTER TABLE digest_entries
    ADD COLUMN version_text VARCHAR(40),
    ADD COLUMN version_sort VARCHAR(32);

CREATE INDEX idx_digest_entries_version ON digest_entries (user_id, version_sort);

CREATE TABLE digest_snapshots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_id    BIGINT    NOT NULL REFERENCES digest_sources(id) ON DELETE CASCADE,
    captured_on  DATE      NOT NULL,
    content_hash CHAR(64)  NOT NULL,
    body         TEXT      NOT NULL,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (source_id, captured_on)
);

CREATE INDEX idx_digest_snapshots_user_day ON digest_snapshots (user_id, captured_on DESC);

CREATE TRIGGER trg_digest_snapshots_notify
    AFTER INSERT OR UPDATE OR DELETE ON digest_snapshots
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
