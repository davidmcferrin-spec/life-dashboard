-- Platform bundle: sector grants, morning briefs, a link graph, and health rows.
-- A missing grant is deny. Allow once is consumed after one successful act.
-- Allow always stays, and the audit log still records the act.
-- Nothing here transfers money. Health device data is copied from Open Wearables.

CREATE TABLE sector_grants (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    principal_kind  VARCHAR(16)  NOT NULL CHECK (principal_kind IN ('token', 'oauth')),
    principal_id    BIGINT       NOT NULL,
    sector          VARCHAR(16)  NOT NULL CHECK (sector IN ('money', 'home', 'mail', 'agents', 'health')),
    mode            VARCHAR(16)  NOT NULL CHECK (mode IN ('deny', 'once', 'always')),
    last_used_at    TIMESTAMP(0),
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, principal_kind, principal_id, sector)
);
CREATE INDEX idx_sector_grants_user ON sector_grants (user_id, principal_kind, principal_id);

CREATE TABLE morning_briefs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    composed_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    body         TEXT         NOT NULL,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_morning_briefs_user ON morning_briefs (user_id, id DESC);

CREATE TABLE brief_schedules (
    user_id      BIGINT      PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    enabled      SMALLINT    NOT NULL DEFAULT 0 CHECK (enabled IN (0, 1)),
    local_time   VARCHAR(5)  NOT NULL DEFAULT '07:00',
    last_ran_on  DATE,
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TABLE graph_nodes (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind     VARCHAR(16)  NOT NULL CHECK (kind IN ('page', 'bill', 'envelope', 'digest', 'health', 'brief')),
    ref_id   BIGINT       NOT NULL,
    label    VARCHAR(200) NOT NULL,
    UNIQUE (user_id, kind, ref_id)
);
CREATE INDEX idx_graph_nodes_label ON graph_nodes (user_id, kind, label);

CREATE TABLE graph_edges (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_id  BIGINT      NOT NULL REFERENCES graph_nodes(id) ON DELETE CASCADE,
    to_id    BIGINT      NOT NULL REFERENCES graph_nodes(id) ON DELETE CASCADE,
    kind     VARCHAR(16) NOT NULL CHECK (kind IN ('wikilink', 'mention', 'related', 'manual')),
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, from_id, to_id, kind),
    CHECK (from_id <> to_id)
);
CREATE INDEX idx_graph_edges_from ON graph_edges (user_id, from_id);
CREATE INDEX idx_graph_edges_to ON graph_edges (user_id, to_id);

CREATE TABLE health_daily (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day                   DATE             NOT NULL,
    sleep_minutes         DOUBLE PRECISION,
    hrv_ms                DOUBLE PRECISION,
    resting_hr            DOUBLE PRECISION,
    steps                 DOUBLE PRECISION,
    readiness_score       SMALLINT         CHECK (readiness_score IS NULL OR readiness_score BETWEEN 0 AND 100),
    readiness_confidence  DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (readiness_confidence >= 0 AND readiness_confidence <= 1),
    sleep_authority       VARCHAR(32),
    hrv_authority         VARCHAR(32),
    resting_authority     VARCHAR(32),
    steps_authority       VARCHAR(32),
    updated_at            TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, day)
);
CREATE INDEX idx_health_daily_user ON health_daily (user_id, day DESC);

CREATE TABLE health_points (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    metric      VARCHAR(16)      NOT NULL CHECK (metric IN ('sleep', 'hrv', 'resting_hr', 'steps', 'body', 'meal')),
    day         DATE             NOT NULL,
    value       DOUBLE PRECISION,
    unit        VARCHAR(16)      NOT NULL,
    authority   VARCHAR(32)      NOT NULL,
    provenance  JSONB            NOT NULL DEFAULT '{}'::jsonb,
    note        TEXT,
    dedupe_key  VARCHAR(160)     NOT NULL,
    created_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dedupe_key)
);
CREATE INDEX idx_health_points_day ON health_points (user_id, metric, day DESC);

CREATE TABLE health_workouts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title        VARCHAR(80)      NOT NULL,
    started_at   TIMESTAMP(0)     NOT NULL,
    ended_at     TIMESTAMP(0),
    minutes      DOUBLE PRECISION CHECK (minutes IS NULL OR minutes >= 0),
    authority    VARCHAR(32)      NOT NULL,
    provenance   JSONB            NOT NULL DEFAULT '{}'::jsonb,
    dedupe_key   VARCHAR(160)     NOT NULL,
    created_at   TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dedupe_key)
);
CREATE INDEX idx_health_workouts_user ON health_workouts (user_id, started_at DESC);

CREATE TABLE health_briefs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    day        DATE         NOT NULL,
    body       TEXT         NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, day)
);

CREATE TABLE health_sync (
    user_id     BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    last_ok_at  TIMESTAMP(0),
    last_error  TEXT,
    last_at     TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
