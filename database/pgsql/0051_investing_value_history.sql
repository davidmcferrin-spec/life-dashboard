-- One observed portfolio total per user per day.
-- market_value is null when that total is unknown. cash is buying power
-- only after it is recorded here. This table does not place an order.

CREATE TABLE invest_value_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    as_of        DATE   NOT NULL,
    market_value DOUBLE PRECISION,
    cash         DOUBLE PRECISION,
    UNIQUE (user_id, as_of)
);

CREATE TRIGGER trg_invest_value_history_notify
    AFTER INSERT OR UPDATE OR DELETE ON invest_value_history
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
