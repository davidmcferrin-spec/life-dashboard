-- =====================================================================
-- L4: personal markdown vault.
-- Full-text uses to_tsvector. Embeddings stay JSON so a missing pgvector
-- install still works; cosine similarity is computed in the app.
-- =====================================================================

CREATE TABLE pages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title       VARCHAR(200) NOT NULL,
    slug        VARCHAR(200) NOT NULL,
    kind        VARCHAR(16)  NOT NULL DEFAULT 'note'
                CHECK (kind IN ('note', 'daily', 'project', 'reference', 'review')),
    body        TEXT         NOT NULL DEFAULT '',
    archived_at TIMESTAMP(0),
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, slug)
);
CREATE INDEX idx_pages_user_updated ON pages(user_id, updated_at DESC) WHERE archived_at IS NULL;
CREATE INDEX idx_pages_fts ON pages USING GIN (to_tsvector('english', title || ' ' || body));

CREATE TABLE page_revisions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id    BIGINT       NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    version    INTEGER      NOT NULL,
    title      VARCHAR(200) NOT NULL,
    body       TEXT         NOT NULL,
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (page_id, version)
);

CREATE TABLE page_links (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_page_id BIGINT       NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    to_page_id   BIGINT       REFERENCES pages(id) ON DELETE SET NULL,
    to_title     VARCHAR(200) NOT NULL,
    UNIQUE (from_page_id, to_title)
);
CREATE INDEX idx_page_links_to ON page_links(user_id, to_page_id);

CREATE TABLE page_embeddings (
    page_id    BIGINT PRIMARY KEY REFERENCES pages(id) ON DELETE CASCADE,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    model      VARCHAR(64)  NOT NULL,
    embedding  JSONB        NOT NULL,
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TRIGGER trg_pages_notify
    AFTER INSERT OR UPDATE OR DELETE ON pages
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
