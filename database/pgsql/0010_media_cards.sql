-- YouTube, Reddit, and X cards for the rotating widgets.
-- Search reads this text. No notify trigger: widget reads must not write in a loop.

CREATE TABLE media_sources (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dataset    VARCHAR(16)  NOT NULL CHECK (dataset IN ('youtube', 'reddit', 'x')),
    source_key VARCHAR(200) NOT NULL,
    label      VARCHAR(200) NOT NULL,
    remote_id  VARCHAR(64),
    last_error TEXT,
    fetched_at TIMESTAMP(0),
    UNIQUE (user_id, dataset, source_key)
);

CREATE TABLE media_cards (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dataset      VARCHAR(16)  NOT NULL CHECK (dataset IN ('youtube', 'reddit', 'x')),
    source_key   VARCHAR(200) NOT NULL,
    external_id  VARCHAR(200) NOT NULL,
    title        VARCHAR(300) NOT NULL,
    body         TEXT         NOT NULL DEFAULT '',
    url          TEXT         NOT NULL,
    published_at TIMESTAMP(0),
    fetched_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dataset, external_id)
);
CREATE INDEX idx_media_cards_user ON media_cards(user_id, dataset, published_at DESC);
