-- One board for work passed between bots. The event rows are append-only
-- so a status change and its note stay in the thread after the card moves.

CREATE TABLE handoffs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title           VARCHAR(200) NOT NULL,
    body            TEXT         NOT NULL DEFAULT '',
    from_agent      VARCHAR(80)  NOT NULL,
    to_agent        VARCHAR(80),
    status          VARCHAR(16)  NOT NULL DEFAULT 'open'
                    CHECK (status IN ('open', 'claimed', 'in_progress', 'blocked', 'done', 'cancelled')),
    priority        VARCHAR(8)   NOT NULL DEFAULT 'normal'
                    CHECK (priority IN ('low', 'normal', 'high')),
    due_at          TIMESTAMP(0),
    tags            TEXT[]       NOT NULL DEFAULT '{}',
    linked_page_ids BIGINT[]     NOT NULL DEFAULT '{}',
    linked_urls     TEXT[]       NOT NULL DEFAULT '{}',
    claimed_by      VARCHAR(80),
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_handoffs_user_updated ON handoffs (user_id, updated_at DESC, id DESC);
CREATE INDEX idx_handoffs_user_status ON handoffs (user_id, status);

CREATE TABLE handoff_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    handoff_id  BIGINT       NOT NULL REFERENCES handoffs(id) ON DELETE CASCADE,
    kind        VARCHAR(16)  NOT NULL
                CHECK (kind IN ('created', 'comment', 'status', 'claim', 'reassign', 'close')),
    status      VARCHAR(16)
                CHECK (status IS NULL OR status IN ('open', 'claimed', 'in_progress', 'blocked', 'done', 'cancelled')),
    body        TEXT         NOT NULL DEFAULT '',
    sender      VARCHAR(80)  NOT NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_handoff_events_thread ON handoff_events (user_id, handoff_id, id);
