-- Locked rows for the mixtape builder.
-- One draft per user. A locked track stays in its slot when the plan is rebuilt.
-- lifedash_notify() reads id and user_id.

CREATE TABLE spotify_mixtape_locks (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    spotify_track_id  VARCHAR(64)  NOT NULL,
    position          SMALLINT     NOT NULL CHECK (position >= 0),
    updated_at        TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, spotify_track_id),
    UNIQUE (user_id, position)
);

CREATE INDEX idx_spotify_mixtape_locks_user ON spotify_mixtape_locks (user_id, position);

CREATE TRIGGER trg_spotify_mixtape_locks_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_mixtape_locks
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
