-- Private vault images. A row belongs to one user.
-- Bytes live under storage/uploads/vault, outside the web root.

CREATE TABLE page_images (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    storage_id  VARCHAR(32)  NOT NULL UNIQUE,
    ext         VARCHAR(8)   NOT NULL,
    mime_type   VARCHAR(64)  NOT NULL,
    size_bytes  BIGINT       NOT NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (ext IN ('jpg', 'png', 'gif', 'webp')),
    CHECK (size_bytes > 0 AND size_bytes <= 8388608)
);

CREATE INDEX idx_page_images_user ON page_images (user_id, id DESC);
