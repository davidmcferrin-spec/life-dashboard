-- Rows the header bell lists for the signed-in user.
-- id and user_id let lifedash_notify name the row.

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title      VARCHAR(160) NOT NULL,
    body       TEXT NOT NULL DEFAULT '',
    href       VARCHAR(2000),
    read_at    TIMESTAMP(0),
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE INDEX idx_notifications_user_recent ON notifications (user_id, created_at DESC, id DESC);

CREATE TRIGGER trg_notifications_notify
    AFTER INSERT OR UPDATE OR DELETE ON notifications
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
