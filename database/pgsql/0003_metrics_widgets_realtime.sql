-- =====================================================================
-- L1 core platform: generic time series, widget grid, realtime events.
--
--   metrics            what is tracked (habit, mood scale, number, duration…)
--   datapoints         the time series; dedupe_key makes writes idempotent
--   dashboard_widgets  every card on the grid (legacy + native types)
--   widget_revisions   append-only history of widget title/config (rollback)
--   lifedash_notify()  pg_notify('lifedash_events', …) on every change —
--                      consumed by the Python lifedash-push service
-- =====================================================================

CREATE TABLE metrics (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    key         VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    -- habit: one 0/1 value per local day · scale: bounded rating (mood)
    -- number: free numeric · duration: seconds
    kind        VARCHAR(16)  NOT NULL CHECK (kind IN ('habit', 'scale', 'number', 'duration')),
    unit        VARCHAR(32),
    config      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    created_by  VARCHAR(16)  NOT NULL DEFAULT 'user' CHECK (created_by IN ('user', 'ai', 'system', 'integration')),
    archived_at TIMESTAMP(0),
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, key),
    CHECK (key ~ '^[a-z0-9][a-z0-9_.-]{0,63}$')
);
CREATE INDEX idx_metrics_user_active ON metrics(user_id, sort_order) WHERE archived_at IS NULL;

CREATE TABLE datapoints (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_id   BIGINT           NOT NULL REFERENCES metrics(id) ON DELETE CASCADE,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    ts          TIMESTAMP(0)     NOT NULL,          -- UTC
    local_date  DATE             NOT NULL,          -- calendar day in APP_TIMEZONE at ts
    value       DOUBLE PRECISION NOT NULL,
    note        TEXT,
    source      VARCHAR(16)      NOT NULL DEFAULT 'manual'
                CHECK (source IN ('manual', 'widget', 'api', 'ai', 'integration', 'import')),
    -- Idempotency: same (metric, dedupe_key) is an upsert, not a new row.
    -- Habits use the local date; integrations can pass their own event id.
    dedupe_key  VARCHAR(128),
    meta        JSONB            NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (metric_id, dedupe_key)
);
CREATE INDEX idx_datapoints_metric_ts   ON datapoints(metric_id, ts DESC);
CREATE INDEX idx_datapoints_metric_date ON datapoints(metric_id, local_date);
CREATE INDEX idx_datapoints_user_ts     ON datapoints(user_id, ts DESC);

CREATE TABLE dashboard_widgets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    board       VARCHAR(32)  NOT NULL DEFAULT 'home',
    type        VARCHAR(48)  NOT NULL,
    title       VARCHAR(128),
    config      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    version     INTEGER      NOT NULL DEFAULT 1,
    -- 12-column grid
    grid_x      SMALLINT     NOT NULL DEFAULT 0 CHECK (grid_x BETWEEN 0 AND 11),
    grid_y      INTEGER      NOT NULL DEFAULT 0 CHECK (grid_y >= 0),
    grid_w      SMALLINT     NOT NULL DEFAULT 4 CHECK (grid_w BETWEEN 1 AND 12),
    grid_h      SMALLINT     NOT NULL DEFAULT 4 CHECK (grid_h BETWEEN 1 AND 24),
    created_by  VARCHAR(16)  NOT NULL DEFAULT 'user' CHECK (created_by IN ('user', 'ai', 'system')),
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (grid_x + grid_w <= 12)
);
CREATE INDEX idx_dashboard_widgets_user_board ON dashboard_widgets(user_id, board, grid_y, grid_x);

CREATE TABLE widget_revisions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    widget_id   BIGINT       NOT NULL REFERENCES dashboard_widgets(id) ON DELETE CASCADE,
    version     INTEGER      NOT NULL,
    title       VARCHAR(128),
    config      JSONB        NOT NULL,
    changed_by  VARCHAR(16)  NOT NULL DEFAULT 'user' CHECK (changed_by IN ('user', 'ai', 'system')),
    note        VARCHAR(255),
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (widget_id, version)
);

-- ---------------------------------------------------------------------
-- Realtime: one channel, small JSON payloads (pg_notify limit is 8000 bytes).
-- Receivers re-fetch through the API; payloads carry ids, never data.
-- ---------------------------------------------------------------------
CREATE FUNCTION lifedash_notify() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    rec     RECORD;
    payload JSONB;
BEGIN
    IF TG_OP = 'DELETE' THEN
        rec := OLD;
    ELSE
        rec := NEW;
    END IF;

    payload := jsonb_build_object(
        'table',   TG_TABLE_NAME,
        'op',      lower(TG_OP),
        'id',      rec.id,
        'user_id', rec.user_id
    );
    IF TG_TABLE_NAME = 'datapoints' THEN
        payload := payload || jsonb_build_object('metric_id', rec.metric_id);
    END IF;

    PERFORM pg_notify('lifedash_events', payload::text);
    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_metrics_notify
    AFTER INSERT OR UPDATE OR DELETE ON metrics
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_datapoints_notify
    AFTER INSERT OR UPDATE OR DELETE ON datapoints
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_dashboard_widgets_notify
    AFTER INSERT OR UPDATE OR DELETE ON dashboard_widgets
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
