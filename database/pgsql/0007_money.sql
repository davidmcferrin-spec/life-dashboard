-- =====================================================================
-- L5: accounts, signed transactions, daily net-worth snapshots.
-- amount < 0 is an outflow. Credit balances are stored as a positive
-- amount owed; net worth subtracts them.
-- =====================================================================

CREATE TABLE money_accounts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(80)      NOT NULL,
    kind        VARCHAR(16)      NOT NULL DEFAULT 'checking'
                CHECK (kind IN ('checking', 'savings', 'credit', 'cash', 'investment', 'other')),
    balance     DOUBLE PRECISION NOT NULL DEFAULT 0,
    archived_at TIMESTAMP(0),
    created_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, name)
);

CREATE TABLE money_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id BIGINT           NOT NULL REFERENCES money_accounts(id) ON DELETE CASCADE,
    posted_on  DATE             NOT NULL,
    amount     DOUBLE PRECISION NOT NULL,
    payee      VARCHAR(160),
    category   VARCHAR(80)      NOT NULL DEFAULT 'Uncategorized',
    note       TEXT,
    dedupe_key VARCHAR(160),
    source     VARCHAR(16)      NOT NULL DEFAULT 'manual'
               CHECK (source IN ('manual', 'import', 'ai')),
    created_at TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dedupe_key)
);
CREATE INDEX idx_money_tx_user_date ON money_transactions(user_id, posted_on DESC);

CREATE TABLE money_snapshots (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    as_of     DATE             NOT NULL,
    net_worth DOUBLE PRECISION NOT NULL,
    UNIQUE (user_id, as_of)
);

CREATE TRIGGER trg_money_accounts_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_accounts
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_transactions_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_transactions
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
