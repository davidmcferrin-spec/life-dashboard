-- Pairwise meal components. A pairing is stored once, with the lower id first.
-- No food rows are inserted here.

CREATE TABLE meal_components (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name       VARCHAR(160) NOT NULL,
    category   VARCHAR(16)  NOT NULL CHECK (category IN (
                   'protein', 'base', 'sauce', 'side', 'aromatic', 'vegetable', 'spice'
               )),
    product_id BIGINT       REFERENCES pantry_products(id) ON DELETE SET NULL,
    notes      TEXT,
    source     VARCHAR(16)  NOT NULL CHECK (source IN ('david', 'past_meal', 'research')),
    created_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_meal_components_user_category ON meal_components(user_id, category, name);

CREATE TABLE meal_pairings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    component_a BIGINT       NOT NULL REFERENCES meal_components(id) ON DELETE CASCADE,
    component_b BIGINT       NOT NULL REFERENCES meal_components(id) ON DELETE CASCADE,
    score       SMALLINT     CHECK (score IS NULL OR (score >= 1 AND score <= 5)),
    note        TEXT,
    source      VARCHAR(16)  NOT NULL CHECK (source IN ('david', 'past_meal', 'research')),
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CHECK (component_a < component_b),
    UNIQUE (user_id, component_a, component_b)
);
CREATE INDEX idx_meal_pairings_b ON meal_pairings(user_id, component_b);
