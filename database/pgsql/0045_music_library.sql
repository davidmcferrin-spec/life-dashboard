-- Genre tags and loudness samples for the track library, plus the activity log.
-- Loudness stays null when Spotify does not return segment levels.
-- lifedash_notify() reads id and user_id.

ALTER TABLE spotify_track_meta
    ADD COLUMN genre_tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN loudness JSONB,
    ADD CONSTRAINT spotify_track_meta_genre_tags_array CHECK (jsonb_typeof(genre_tags) = 'array'),
    ADD CONSTRAINT spotify_track_meta_loudness_array CHECK (loudness IS NULL OR jsonb_typeof(loudness) = 'array');

CREATE TABLE spotify_library_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    action          VARCHAR(32)  NOT NULL CHECK (action IN ('reanalyze', 'set_season', 'add_playlist', 'genre')),
    title           TEXT         NOT NULL,
    summary         TEXT         NOT NULL,
    href            TEXT,
    undo_payload    JSONB,
    undone_at       TIMESTAMP(0),
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_spotify_library_log_user ON spotify_library_log(user_id, id DESC);

CREATE TRIGGER trg_spotify_library_log_notify
    AFTER INSERT OR UPDATE OR DELETE ON spotify_library_log
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
