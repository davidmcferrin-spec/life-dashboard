-- Freshness, debt components, payment status, expected inflows, benefit pots,
-- and a category override layer. Existing transaction rows and debt balances
-- are not rewritten. A component total that disagrees with the balance is
-- flagged on read. A category change is stored beside the imported category.
-- Stale hours and food targets are per-user numbers, not environment variables.

ALTER TABLE money_accounts
    ADD COLUMN last_synced_at TIMESTAMP(0),
    ADD COLUMN sync_provider VARCHAR(32);

ALTER TABLE money_debts
    ADD COLUMN last_synced_at TIMESTAMP(0);

ALTER TABLE money_transactions
    ADD COLUMN eaten_on DATE;

CREATE INDEX idx_money_tx_eaten ON money_transactions (user_id, eaten_on);

CREATE TABLE money_debt_components (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debt_id          BIGINT NOT NULL UNIQUE REFERENCES money_debts(id) ON DELETE CASCADE,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    principal        DOUBLE PRECISION CHECK (principal IS NULL OR principal >= 0),
    unapplied_funds  DOUBLE PRECISION CHECK (unapplied_funds IS NULL OR unapplied_funds >= 0),
    late_charges     DOUBLE PRECISION CHECK (late_charges IS NULL OR late_charges >= 0),
    fees             DOUBLE PRECISION CHECK (fees IS NULL OR fees >= 0),
    interest         DOUBLE PRECISION CHECK (interest IS NULL OR interest >= 0),
    updated_at       TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_money_debt_components_user ON money_debt_components (user_id);

CREATE TABLE money_payments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    bill_id         BIGINT REFERENCES money_bills(id) ON DELETE CASCADE,
    debt_id         BIGINT REFERENCES money_debts(id) ON DELETE CASCADE,
    amount          DOUBLE PRECISION NOT NULL CHECK (amount >= 0),
    status          VARCHAR(16) NOT NULL CHECK (status IN ('scheduled', 'pending', 'posted', 'failed')),
    due_on          DATE,
    note            TEXT,
    transaction_id  BIGINT REFERENCES money_transactions(id) ON DELETE SET NULL,
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    CONSTRAINT money_payments_target_chk CHECK (bill_id IS NOT NULL OR debt_id IS NOT NULL)
);
CREATE INDEX idx_money_payments_user ON money_payments (user_id, status, due_on);

CREATE TABLE money_expected_inflows (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind            VARCHAR(24) NOT NULL CHECK (kind IN ('reimbursement', 'paycheck', 'refund', 'other')),
    source          VARCHAR(160) NOT NULL,
    amount          DOUBLE PRECISION NOT NULL CHECK (amount >= 0),
    expected_on     DATE NOT NULL,
    status          VARCHAR(16) NOT NULL DEFAULT 'expected' CHECK (status IN ('expected', 'received', 'cancelled')),
    transaction_id  BIGINT REFERENCES money_transactions(id) ON DELETE SET NULL,
    received_on     DATE,
    note            TEXT,
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE INDEX idx_money_inflows_user ON money_expected_inflows (user_id, status, expected_on);

CREATE TABLE money_benefit_pots (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind               VARCHAR(8) NOT NULL CHECK (kind IN ('fsa', 'hsa')),
    name               VARCHAR(80) NOT NULL,
    balance            DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (balance >= 0),
    plan_year          SMALLINT NOT NULL CHECK (plan_year BETWEEN 2000 AND 2100),
    deadline           DATE,
    use_it_or_lose_it  DOUBLE PRECISION CHECK (use_it_or_lose_it IS NULL OR use_it_or_lose_it >= 0),
    last_synced_at     TIMESTAMP(0),
    archived_at        TIMESTAMP(0),
    created_at         TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at         TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, kind, name, plan_year)
);
CREATE INDEX idx_money_benefit_pots_user ON money_benefit_pots (user_id, archived_at);

-- The imported category stays on money_transactions. This row is what reads show.
CREATE TABLE money_category_overrides (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    transaction_id  BIGINT NOT NULL REFERENCES money_transactions(id) ON DELETE CASCADE,
    category        VARCHAR(80) NOT NULL,
    category_id     BIGINT REFERENCES money_categories(id) ON DELETE SET NULL,
    created_at      TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, transaction_id)
);

CREATE TABLE money_merchant_rules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    merchant     VARCHAR(160) NOT NULL,
    category     VARCHAR(80) NOT NULL,
    category_id  BIGINT REFERENCES money_categories(id) ON DELETE SET NULL,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);
CREATE UNIQUE INDEX idx_money_merchant_rules_name ON money_merchant_rules (user_id, lower(merchant));

CREATE TABLE money_user_options (
    user_id            BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    stale_hours        INTEGER NOT NULL DEFAULT 24 CHECK (stale_hours BETWEEN 1 AND 8760),
    groceries_weekly   DOUBLE PRECISION NOT NULL DEFAULT 150 CHECK (groceries_weekly >= 0),
    eating_out_weekly  DOUBLE PRECISION NOT NULL DEFAULT 125 CHECK (eating_out_weekly >= 0),
    updated_at         TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

CREATE TRIGGER trg_money_debt_components_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_debt_components
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_payments_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_payments
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_inflows_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_expected_inflows
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_benefit_pots_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_benefit_pots
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_category_overrides_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_category_overrides
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_merchant_rules_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_merchant_rules
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_money_user_options_notify
    AFTER INSERT OR UPDATE OR DELETE ON money_user_options
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify_user();
