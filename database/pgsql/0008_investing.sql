-- =====================================================================
-- L6: read-only positions and activity. Nothing here places an order.
-- Polymarket rows are refreshed from the public data API.
-- =====================================================================

CREATE TABLE invest_positions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    venue      VARCHAR(32)      NOT NULL,
    symbol     VARCHAR(80)      NOT NULL,
    quantity   DOUBLE PRECISION NOT NULL DEFAULT 0,
    avg_cost   DOUBLE PRECISION NOT NULL DEFAULT 0,
    mark       DOUBLE PRECISION NOT NULL DEFAULT 0,
    meta       JSONB            NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, venue, symbol)
);

CREATE TABLE invest_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT           NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    venue       VARCHAR(32)      NOT NULL,
    symbol      VARCHAR(80),
    kind        VARCHAR(32)      NOT NULL,
    quantity    DOUBLE PRECISION,
    amount      DOUBLE PRECISION,
    occurred_on DATE             NOT NULL,
    note        TEXT,
    dedupe_key  VARCHAR(160),
    created_at  TIMESTAMP(0)     NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, dedupe_key)
);
CREATE INDEX idx_invest_activity_user_date ON invest_activity(user_id, occurred_on DESC);

CREATE TABLE invest_wallets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    venue      VARCHAR(32) NOT NULL,
    address    VARCHAR(80) NOT NULL,
    updated_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC'),
    UNIQUE (user_id, venue)
);

CREATE TRIGGER trg_invest_positions_notify
    AFTER INSERT OR UPDATE OR DELETE ON invest_positions
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();

CREATE TRIGGER trg_invest_activity_notify
    AFTER INSERT OR UPDATE OR DELETE ON invest_activity
    FOR EACH ROW EXECUTE FUNCTION lifedash_notify();
