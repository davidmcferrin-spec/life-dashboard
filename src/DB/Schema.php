    /** Arbitrary constant for pg_advisory_xact_lock (ASCII "LIFEDASH" as an int64). */
    private const PG_MIGRATION_LOCK_KEY = 5497002083494220616;

    public function __construct(private readonly Database $db) {}

    /**
     * Run all migrations in order. Safe to re-run (idempotent).
     */
    public function migrate(bool $quiet = false): void
    {
        $this->createMigrationsTable();

        if ($this->db->isPgsql()) {
            $this->runPgsqlPending($quiet);
            return;
        }

        $this->runPending($quiet);
    }

    /** Directory holding versioned PostgreSQL migrations (NNNN_name.sql). */
    public static function pgsqlMigrationsDir(): string
    {
        return ROOT_DIR . '/database/pgsql';
    }

    /**
     * PostgreSQL migrations, sorted by file name.
     * Keys are the file stem (e.g. "0001_baseline") and are recorded in `migrations.name`.
     *
     * @return array<string, string> name => absolute path
     */
    public static function pgsqlMigrationFiles(?string $dir = null): array
    {
        $dir   = $dir ?? self::pgsqlMigrationsDir();
        $files = glob($dir . '/*.sql') ?: [];
        sort($files, SORT_STRING);

        $out = [];
        foreach ($files as $file) {
            $name = basename($file, '.sql');
            if (!preg_match('/^\d{4}_[a-z0-9_]+$/', $name)) {
                throw new \RuntimeException("Invalid PostgreSQL migration file name: {$name}.sql (expected NNNN_snake_case.sql)");
            }
            $out[$name] = $file;
        }

        return $out;
    }

    /**
     * Apply pending PostgreSQL migrations. Each file runs in its own
     * transaction (PostgreSQL DDL is transactional), so a failure leaves the
     * schema exactly as it was before that file.
     */
    private function runPgsqlPending(bool $quiet = false): void
    {
        $ranNames = array_column($this->db->fetchAll('SELECT name FROM migrations'), 'name');

        foreach (self::pgsqlMigrationFiles() as $name => $file) {
            if (in_array($name, $ranNames, true)) {
                continue;
            }

            $sql = file_get_contents($file);
            if ($sql === false || trim($sql) === '') {
                throw new \RuntimeException("PostgreSQL migration {$name} is empty or unreadable.");
            }

            $applied = $this->db->transaction(function (Database $db) use ($name, $sql): bool {
                // Serialise concurrent migrators (deploy script vs. a stray AUTO_MIGRATE request).
                $db->fetchScalar('SELECT pg_advisory_xact_lock(?)', [self::PG_MIGRATION_LOCK_KEY]);
                if ($db->fetchOne('SELECT 1 FROM migrations WHERE name = ?', [$name]) !== null) {
                    return false; // another process applied it while we waited
                }
                // exec() uses the simple query protocol, which allows multiple statements.
                $db->pdo()->exec($sql);
                $db->execute('INSERT INTO migrations (name) VALUES (?)', [$name]);
                return true;
            });

            if ($applied && !$quiet) {
                echo "  ✓ {$name}\n";
            }
        }
    }

    private function createMigrationsTable(): void
    {
        if ($this->db->isPgsql()) {
            $this->db->execute("
                CREATE TABLE IF NOT EXISTS migrations (
                    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name   VARCHAR(255) NOT NULL UNIQUE,
                    ran_at TIMESTAMP(0) NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
                )
            ");
            return;
        }

        // sql-lint:ignore — SQLite/MySQL legacy path
        $this->db->execute("
            CREATE TABLE IF NOT EXISTS migrations (
                id         INTEGER PRIMARY KEY AUTOINCREMENT,
                name       VARCHAR(255) NOT NULL UNIQUE,
                ran_at     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        ");
    }

