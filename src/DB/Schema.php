    private function runPending(bool $quiet = false): void
    {
        $ran = $this->db->fetchAll('SELECT name FROM migrations');
        $ranNames = array_column($ran, 'name');

        foreach ($this->migrations() as $name => $sql) {
            if (in_array($name, $ranNames, true)) {
                continue;
            }

            $this->db->transaction(function (Database $db) use ($name, $sql): void {
                $db->execute(trim($sql));
                $db->execute(
                    'INSERT INTO migrations (name) VALUES (?)',
                    [$name]
                );
            });

            if (!$quiet) {
                echo "  ✓ {$name}\n";
            }
        }
    }

