    /**
     * Seed Work / Personal / Home todo lists for users with none. Safe to re-run.
     */
    public function seedDefaultTodoLists(): void
    {
        if (!$this->db->tableExists('user_todo_lists')) {
            return;
        }

        $defaults = [
            ['name' => 'Work',     'slug' => 'work',     'sort_order' => 0, 'pin' => 1],
            ['name' => 'Personal', 'slug' => 'personal', 'sort_order' => 1, 'pin' => 1],
            ['name' => 'Home',     'slug' => 'home',     'sort_order' => 2, 'pin' => 1],
        ];

        $users = $this->db->fetchAll('SELECT id FROM users');
        $seeded = 0;

        foreach ($users as $row) {
            $userId = (int) $row['id'];
            $count  = (int) $this->db->fetchScalar(
                'SELECT COUNT(*) FROM user_todo_lists WHERE user_id = ?',
                [$userId]
            );

            if ($count > 0) {
                continue;
            }

            foreach ($defaults as $list) {
                $this->db->execute(
                    'INSERT INTO user_todo_lists (user_id, name, slug, sort_order, pin_to_dashboard)
                     VALUES (?, ?, ?, ?, ?)',
                    [$userId, $list['name'], $list['slug'], $list['sort_order'], $list['pin']]
                );
            }

            $seeded++;
        }

        echo "  ✓ Default todo lists: {$seeded} user(s) seeded\n";
    }

    /**
     * Per-user flags so clearing widget data does not re-insert demo rows.
     * Safe to re-run; only sets flags for users who lack them.
     */
    public function markWidgetDefaultsSeededForExistingUsers(): void
    {
        $prefs = new PreferenceService($this->db);
        $users = $this->db->fetchAll('SELECT id FROM users');
        $marked = 0;

        foreach ($users as $row) {
            $userId = (int) $row['id'];
            foreach (array_keys(PreferenceService::WIDGET_DEFAULTS_SEEDED_KEYS) as $widget) {
                if (!$prefs->hasWidgetDefaultsSeeded($userId, $widget)) {
                    $prefs->markWidgetDefaultsSeeded($userId, $widget);
                    $marked++;
                }
            }
        }

        echo '  ✓ Widget default-seed flags: ' . count($users) . ' user(s), ' . $marked . " flag(s) set\n";
    }

