    /**
     * Pin stock symbols on the dashboard for users with none pinned (up to widget max).
     */
    public function seedStocksDashboardPins(): void
    {
        if (!$this->db->tableExists('user_stock_symbols')) {
            return;
        }

        $widgetMax = \Dashboard\Stock\StockService::widgetMaxSymbols();

        $users = $this->db->fetchAll('SELECT id FROM users');
        $updated = 0;

        foreach ($users as $row) {
            $userId = (int) $row['id'];
            $pinned = (int) $this->db->fetchScalar(
                'SELECT COUNT(*) FROM user_stock_symbols WHERE user_id = ? AND pin_to_dashboard = 1',
                [$userId]
            );

            if ($pinned > 0) {
                continue;
            }

            $symbols = $this->db->fetchAll(
                'SELECT id FROM user_stock_symbols WHERE user_id = ? ORDER BY sort_order ASC, symbol ASC LIMIT ' . (int) $widgetMax,
                [$userId]
            );

            foreach ($symbols as $symbol) {
                $this->db->execute(
                    'UPDATE user_stock_symbols SET pin_to_dashboard = 1 WHERE id = ? AND user_id = ?',
                    [(int) $symbol['id'], $userId]
                );
            }

            if ($symbols !== []) {
                $updated++;
            }
        }

        echo "  ✓ Stock dashboard pins: {$updated} user(s) updated\n";
    }
